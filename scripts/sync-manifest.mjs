/**
 * Single source: parse LESSONS from src/data/lessons.ts → generated/lesson-manifest.ts
 * Also validates basic content consistency.
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const lessonsPath = path.join(root, "src/data/lessons.ts");
const demoPath = path.join(root, "src/data/demo-sources.ts");
const docsPath = path.join(root, "src/data/docs-map.ts");
const outPath = path.join(root, "src/generated/lesson-manifest.ts");

const lessonsSrc = fs.readFileSync(lessonsPath, "utf8");
const slugs = [...lessonsSrc.matchAll(/^\s*slug:\s*"([^"]+)"/gm)].map((m) => m[1]);
const unique = new Set(slugs);
if (unique.size !== slugs.length) {
  const dups = slugs.filter((s, i) => slugs.indexOf(s) !== i);
  console.error("Duplicate slugs:", [...new Set(dups)]);
  process.exit(1);
}

const tracks = [...lessonsSrc.matchAll(/^\s*track:\s*"([^"]+)"/gm)].map((m) => m[1]);
const formats = [...lessonsSrc.matchAll(/^\s*format:\s*"([^"]+)"/gm)].map((m) => m[1]);

const demoKindsUsed = [
  ...new Set([...lessonsSrc.matchAll(/kind:\s*"([^"]+)"/g)].map((m) => m[1])),
];
const demoSrc = fs.readFileSync(demoPath, "utf8");
const missingDemo = demoKindsUsed.filter((k) => !demoSrc.includes(`${k}:`) && !demoSrc.includes(`"${k}"`));
if (missingDemo.length) {
  console.error("Demo kinds missing from demo-sources:", missingDemo);
  process.exit(1);
}

const docs = fs.readFileSync(docsPath, "utf8");
const docSlugs = [...docs.matchAll(/lessonSlug:\s*"([^"]+)"/g)].map((m) => m[1]);
const missingLessons = [...new Set(docSlugs)].filter((s) => !unique.has(s));
if (missingLessons.length) {
  console.error("docs-map lessonSlug missing in LESSONS:", missingLessons);
  process.exit(1);
}

const courseCount = formats.length
  ? formats.filter((f) => f === "course").length
  : slugs.length;
const refCount = formats.filter((f) => f === "reference").length;

const body = `/* AUTO-GENERATED by scripts/sync-manifest.mjs — do not edit by hand */
export const LESSON_SLUGS = ${JSON.stringify(slugs, null, 2)} as const;

export type LessonSlug = (typeof LESSON_SLUGS)[number];

export const LESSON_COUNT = ${slugs.length} as const;

/** 主修课（format: course）；reference 不计入结业硬门槛时可另算 */
export const MANIFEST_META = {
  total: ${slugs.length},
  courseApprox: ${courseCount || slugs.length},
  referenceApprox: ${refCount},
  generatedAt: ${JSON.stringify(new Date().toISOString())},
} as const;
`;

fs.mkdirSync(path.dirname(outPath), { recursive: true });
fs.writeFileSync(outPath, body);
console.log(`Wrote ${outPath} (${slugs.length} slugs)`);
